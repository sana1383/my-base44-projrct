export const getPropertyBySlug = (slug) => properties.find((item) => item.slug === slug)

export const getAgent = (id) => agents.find((agent) => agent.id === id)

export const getSimilarProperties = (property, limit = 3) =>
  properties
    .filter((item) => item.slug !== property.slug)
    .sort((a, b) => {
      const scoreA = (a.type === property.type ? 2 : 0) + (a.city === property.city ? 1 : 0)
      const scoreB = (b.type === property.type ? 2 : 0) + (b.city === property.city ? 1 : 0)
      return scoreB - scoreA
    })
    .slice(0, limit)

